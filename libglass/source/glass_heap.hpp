#pragma once
#include <cstddef>

namespace ryz::glass::heap {

// ПАМЯТЬ ПОД ВИДЕОЧИП: куча процесса ovlloader растёт сразу за кучей оверлея, прибавка — отдельный запас видеочипа.
//
// Своя куча оверлея — обычно 8 МБ (heap_size.bin), свободно в ней около 3 МБ. Видеочипу нужны transfer memory
// nvdrv (3 МБ), два образа свопчейна RGBA8, буфер интерфейса, стекло и память очереди deko3d. Всё это — из прибавки,
// и newlib её не видит: в кучу оверлея видеочип не попадает никогда. Это важно для ovlloader: следующий оверлей он
// читает с карты прямо в эту кучу, и кусок, который ещё держит nvdrv, роняет его (fatal 2347-0004).
// Не дали прибавку — кадр выводит libnx. Возврат системе — в конце __appExit (ryzAfterAppExit в tesla.hpp), если в
// запасе ничего не осталось.

// Зовётся в начале tsl::loop, в одном потоке. Возвращает размер запаса в байтах (0 — не вышло). Прибавку, которую
// прошлый оверлей не вернул, подхватывает, если она целиком обычная куча RW.
// need — сколько нужно видеочипу этого оверлея (зависит от размера его буфера: панель — 8 МБ, полноэкранный HUD — 16).
std::size_t reserve(std::size_t need);
// Для журнала: как прошёл reserve (что не дало запас или откуда он).
const char* reserveStory();
// Из запаса; nullptr — запаса нет или не хватило.
void* alloc(std::size_t size, std::size_t align);
void release(void* p);
bool owns(const void* p);
// Занято сейчас (на выходе должно быть 0).
std::size_t inUse();
// Свободно в запасе (сумма, не наибольший кусок).
std::size_t available();

}  // namespace ryz::glass::heap
